/**
 * Render every documentation page from the graph.
 *
 * @param {object} graph loaded graph index (see ../../lib/graph_load.mjs).
 * @param {{lang?: string, docsPath?: string, agentsLink?: string, descriptions?: object}} [opts]
 *   `docsPath` is how AGENTS.md (at the repo root) reaches the docs directory,
 *   `agentsLink` how the docs index reaches AGENTS.md — both are plain link
 *   prefixes, resolved by the caller that knows where the files land.
 *   `descriptions` is a store from ../../describe/lib/store.mjs; when given, the
 *   MODEL-WRITTEN description of each domain is rendered in its own labelled
 *   section, never mixed into a line of proven facts.
 * @returns {Array<{kind: string, path: string, content: string}>} bodies WITHOUT
 *   the generated-block markers; `path` is 'AGENTS.md' for the entry point
 *   (repo root) and relative to the docs dir for every other page.
 */
export function renderDocs(graph, {
  lang = DEFAULT_LANG, docsPath = 'docs/loregraph', agentsLink, descriptions,
} = {}) {
  const t = translator(lang);
  const { name: project, rev } = identity(graph);

  // Normalize the link prefix once: '' or 'a/b/' — never 'a/b'.
  const prefix = docsPath ? `${String(docsPath).replace(/\/+$/, '')}/` : '';
  const upToRoot = agentsLink ?? `${'../'.repeat(prefix ? prefix.split('/').filter(Boolean).length : 0)}AGENTS.md`;

  // Stable page names, deduped in case two domain names slugify alike.
  const used = new Set();
  const domains = domainFacts(graph).map((d) => {
    let slug = slugify(d.name);
    if (used.has(slug)) {
      let i = 2;
      while (used.has(`${slug}-${i}`)) i += 1;
      slug = `${slug}-${i}`;
    }
    used.add(slug);
    return { ...d, page: `${slug}.md` };
  });

  const ctx = { t, lang, rev, project, docsPath: prefix, agentsLink: upToRoot, domains, descriptions };

  return [
    { kind: 'agents', path: 'AGENTS.md', content: renderAgents(graph, ctx) },
    { kind: 'index', path: 'README.md', content: renderIndex(graph, ctx) },
    { kind: 'dependencies', path: 'dependencies.md', content: renderDependencies(graph, ctx) },
    { kind: 'health', path: 'health.md', content: renderHealth(graph, ctx) },
    ...domains.map((d) => ({
      kind: 'domain',
      path: `domains/${d.page}`,
      content: renderDomain(graph, ctx, d),
    })),
  ];
}
