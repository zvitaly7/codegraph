// Render the generated documentation set from a loaded graph.
//
// Pure: graph + options in, `[{ kind, path, content }]` out — no I/O, no clock,
// no randomness, so two runs on the same cache produce byte-identical bodies
// (that is what makes `loregraph docs` idempotent).
//
// The pages are written FOR AI AGENTS:
//   AGENTS.md        the entry point — what this project is, how big, what the
//                    graph can prove about its tech, the domain map, and the
//                    instruction to reach for `brief`/`impact`/MCP instead of
//                    reading dozens of files.
//   README.md        index of the generated pages.
//   domains/<d>.md   one page per domain.
//   dependencies.md  the cross-domain map plus packages and importers.
//   health.md        dead exports and orphan candidates (heuristics, labelled).
//
// Honesty rule: the graph proves STRUCTURE, not intent. Nothing here narrates
// architecture or purpose — every line is a fact the graph can back up, and
// every page says so in its header.
//
// The ONE exception is a cached description from `loregraph describe`, which is
// model-written. Those are opt-in (you have to have run that command), they live
// in their own clearly-marked section or blockquote rather than beside a proven
// number, and each one names the model, the provider and the date behind it.
//
// Bodies are rendered WITHOUT the generated-block markers; wrapping and merging
// with whatever is already on disk is `./merge.mjs`'s job.

/** How many rows a ranked list shows before it is cut off. */
const TOP_N = 10;
/** How many dead-export rows the health page samples. */
const SAMPLE_N = 20;

/** Extensions the imports layer can actually link, so orphan-hunting is fair. */
const LINKABLE_EXT = new Set(['.js', '.jsx', '.mjs', '.cjs', '.ts', '.tsx', '.mts', '.cts']);
/** File stems that are entry points by convention — never orphan candidates. */
const ENTRY_STEMS = new Set([
  'index', 'main', 'bootstrap', 'entry', 'app', 'server', 'cli', 'worker', 'setup',
]);

