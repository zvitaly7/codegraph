const pathOf = (node) => node?.properties?.path ?? node?.id?.replace(/^file:/, '') ?? '';
const stemOf = (path) => (path.split('/').pop() ?? '').replace(/\.[^.]+$/, '').toLowerCase();
const extOf = (path) => {
  const base = path.split('/').pop() ?? '';
  const i = base.lastIndexOf('.');
  return i > 0 ? base.slice(i).toLowerCase() : '';
};

function isTestFile(node) {
  const path = pathOf(node);
  if (node?.properties?.kind === 'test') return true;
  return /(^|\/)(__tests__|__test__|tests?|spec)\//i.test(path)
    || /\.(test|spec)\.[a-z]+$/i.test(path);
}

/** Entry-like files are expected to have no importers, so they are not orphans. */
function isEntryLike(path) {
  const base = path.split('/').pop() ?? '';
  if (!path.includes('/')) return true;              // top-level script
  if (/\.d\.[cm]?ts$/i.test(base)) return true;      // ambient declarations
  if (/\.config\./i.test(base)) return true;         // tool config
  return ENTRY_STEMS.has(stemOf(path));
}

/** Project name + the revision the cache was built from. */
function identity(graph) {
  const node = graph.byLabel('Project')[0];
  const fromManifest = String(graph.manifest?.projectId ?? '').replace(/^project:/, '');
  const name = node?.properties?.name || fromManifest || 'this repository';

  let rev = graph.manifest?.vcs?.revision ?? null;
  if (!rev || rev === 'no-revision') {
    const snapshotId = graph.manifest?.snapshotId;
    const i = typeof snapshotId === 'string' ? snapshotId.lastIndexOf(':') : -1;
    rev = i !== -1 ? snapshotId.slice(i + 1) : null;
  }
  return { name, rev: rev && rev !== 'no-revision' ? rev : 'unknown' };
}

/** Distinct files importing each package, ranked. */
function packageRanking(graph) {
  return graph.byLabel('Package')
    .map((p) => ({
      key: p.properties?.name ?? p.id.replace(/^pkg:/, ''),
      n: new Set(graph.neighbors(p.id, { dir: 'in', type: 'IMPORTS' }).map((e) => e.from)).size,
    }))
    .filter((r) => r.n > 0)
    .sort(byCountThenName);
}

/** External package names a set of file ids imports, ranked by importing files. */
function packagesForFiles(graph, fileIds) {
  const counts = new Map();
  for (const id of fileIds) {
    for (const e of graph.neighbors(id, { dir: 'out', type: 'IMPORTS' })) {
      if (!e.to.startsWith('pkg:')) continue;
      const name = graph.getNode(e.to)?.properties?.name ?? e.to.slice('pkg:'.length);
      counts.set(name, (counts.get(name) ?? 0) + 1);
    }
  }
  return [...counts].map(([key, n]) => ({ key, n })).sort(byCountThenName);
}

/** Cross-file REFERENCES to a symbol (same-file uses do not count as demand). */
function crossFileRefs(graph, symId) {
  return new Set(
    graph.neighbors(symId, { dir: 'in', type: 'REFERENCES' })
      .filter((e) => e.properties?.sameFile !== true)
      .map((e) => e.from),
  ).size;
}

/** Every domain with the facts its page and the domain map need. */
function domainFacts(graph) {
  return graph.byLabel('Domain')
    .map((d) => {
      const name = d.properties?.name ?? d.id.replace(/^domain:/, '');
      const fileIds = graph.neighbors(d.id, { dir: 'in', type: 'BELONGS_TO' }).map((e) => e.from).sort();
      const rank = (dir, endpoint) => graph.neighbors(d.id, { dir, type: 'DEPENDS_ON' })
        .map((e) => ({
          key: (graph.getNode(e[endpoint])?.properties?.name) ?? e[endpoint].replace(/^domain:/, ''),
          n: e.properties?.weight ?? 1,
        }))
        .sort(byCountThenName);
      return {
        id: d.id,
        name,
        kind: d.properties?.kind ?? 'unknown',
        fileIds,
        dependsOn: rank('out', 'to'),
        dependedOnBy: rank('in', 'from'),
      };
    })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

/**
 * Exported symbols nothing outside their own file references. Symbols declared
 * in an entry-point file are held back — they are consumed across a boundary the
 * import graph cannot see — and so are symbols an entry point RE-EXPORTS (an
 * EXPOSES edge). Both are counted separately so the omission stays visible.
 */
function deadExportRows(graph) {
  const exported = graph.byLabel('Symbol').filter((n) => n.properties?.exported === true);
  const precise = graph.loadedLayers.includes('references');
  const unreferenced = exported.filter((n) => (precise
    ? graph.neighbors(n.id, { dir: 'in', type: 'REFERENCES' }).every((e) => e.properties?.sameFile === true)
    : graph.neighbors(n.id, { dir: 'in' }).every((e) => e.type === 'DECLARES')));
  const isEntryPoint = (n) => graph.getNode(`file:${n.properties?.path}`)?.properties?.entryPoint === true
    || graph.neighbors(n.id, { dir: 'in', type: 'EXPOSES' }).length > 0;
  const dead = unreferenced.filter((n) => !isEntryPoint(n));
  dead.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return {
    precise,
    exportedTotal: exported.length,
    dead,
    entryPoints: unreferenced.length - dead.length,
  };
}

/** Source files with no importer that do not look like entry points. */
function orphanFiles(graph) {
  return graph.byLabel('File')
    .filter((n) => {
      const path = pathOf(n);
      if (!LINKABLE_EXT.has(extOf(path))) return false;
      if (isTestFile(n)) return false;
      if (isEntryLike(path)) return false;
      return graph.neighbors(n.id, { dir: 'in', type: 'IMPORTS' }).length === 0;
    })
    .map((n) => pathOf(n))
    .sort();
}

