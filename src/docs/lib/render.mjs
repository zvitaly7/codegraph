function renderDomain(graph, ctx, d) {
  const { t, rev, descriptions } = ctx;
  const files = d.fileIds.map((id) => graph.getNode(id)).filter(Boolean);

  const symbolRows = files
    .flatMap((f) => graph.neighbors(f.id, { dir: 'out', type: 'DECLARES' }).map((e) => graph.getNode(e.to)))
    .filter((s) => s?.properties?.exported === true)
    .map((s) => ({ key: s.id, n: crossFileRefs(graph, s.id), node: s }))
    .filter((r) => r.n > 0)
    .sort(byCountThenName);

  const fileRows = files
    .map((f) => ({
      key: pathOf(f),
      n: new Set(graph.neighbors(f.id, { dir: 'in', type: 'IMPORTS' }).map((e) => e.from)).size,
    }))
    .filter((r) => r.n > 0)
    .sort(byCountThenName);

  const pkgs = withMore(packagesForFiles(graph, d.fileIds), t);
  const syms = withMore(symbolRows, t);
  const topFiles = withMore(fileRows, t);

  const out = [
    `# ${t('domainTitle', { name: d.name })}`,
    '',
    header(t, rev),
    '',
    ...describedBlock(t, descriptions, d.id),
    t('domainSummary', { kind: d.kind, files: d.fileIds.length }),
    '',
    `## ${t('domainDependsOn')}`,
    '',
    table([t('colDomain'), t('colWeight')], d.dependsOn.map((x) => [`\`${x.key}\``, x.n]), t),
    '',
    `## ${t('domainDependedOnBy')}`,
    '',
    table([t('colDomain'), t('colWeight')], d.dependedOnBy.map((x) => [`\`${x.key}\``, x.n]), t),
    '',
    `## ${t('domainPackages')}`,
    '',
    table([t('colPackage'), t('colImportedBy')], pkgs.shown.map((p) => [`\`${p.key}\``, p.n]), t),
    ...(pkgs.moreLine ? ['', pkgs.moreLine] : []),
    '',
    `## ${t('domainSymbols')}`,
    '',
    table(
      [t('colSymbol'), t('colKind'), t('colLocation'), t('colRefs')],
      syms.shown.map((s) => [
        `\`${s.node.properties?.name ?? s.node.id}\``,
        `\`${s.node.properties?.kind ?? '?'}\``,
        `\`${s.node.properties?.path ?? ''}:${s.node.properties?.line ?? '?'}\``,
        s.n,
      ]),
      t,
    ),
    ...(syms.moreLine ? ['', syms.moreLine] : []),
    '',
    `## ${t('domainFiles')}`,
    '',
    table([t('colFile'), t('colImportedBy')], topFiles.shown.map((f) => [`\`${f.key}\``, f.n]), t),
    ...(topFiles.moreLine ? ['', topFiles.moreLine] : []),
  ];
  return `${out.join('\n')}\n`;
}

function renderDependencies(graph, ctx) {
  const { t, rev } = ctx;

  const crossDomain = graph.byType('DEPENDS_ON')
    .map((e) => ({
      from: graph.getNode(e.from)?.properties?.name ?? e.from.replace(/^domain:/, ''),
      to: graph.getNode(e.to)?.properties?.name ?? e.to.replace(/^domain:/, ''),
      n: e.properties?.weight ?? 1,
    }))
    .map((r) => ({ ...r, key: `${r.from} -> ${r.to}` }))
    .sort(byCountThenName);

  const importerRows = graph.byLabel('File')
    .map((f) => {
      const out = graph.neighbors(f.id, { dir: 'out', type: 'IMPORTS' });
      const external = out.filter((e) => e.to.startsWith('pkg:')).length;
      return { key: pathOf(f), n: out.length, internal: out.length - external, external };
    })
    .filter((r) => r.n > 0)
    .sort(byCountThenName);

  const deps = withMore(crossDomain, t, TOP_N * 2);
  const pkgs = withMore(packageRanking(graph), t, TOP_N * 2);
  const importers = withMore(importerRows, t);

  const out = [
    `# ${t('dependenciesTitle')}`,
    '',
    header(t, rev),
    '',
    `## ${t('depsCrossDomain')}`,
    '',
    t('depsCrossDomainNote'),
    '',
    table(
      [t('colFrom'), t('colTo'), t('colWeight')],
      deps.shown.map((r) => [`\`${r.from}\``, `\`${r.to}\``, r.n]),
      t,
    ),
    ...(deps.moreLine ? ['', deps.moreLine] : []),
    '',
    `## ${t('depsPackages')}`,
    '',
    table([t('colPackage'), t('colImportedBy')], pkgs.shown.map((p) => [`\`${p.key}\``, p.n]), t),
    ...(pkgs.moreLine ? ['', pkgs.moreLine] : []),
    '',
    `## ${t('depsImporters')}`,
    '',
    table(
      [t('colFile'), t('colImports'), t('colPackage')],
      importers.shown.map((r) => [`\`${r.key}\``, r.internal, r.external]),
      t,
    ),
    ...(importers.moreLine ? ['', importers.moreLine] : []),
  ];
  return `${out.join('\n')}\n`;
}

function renderHealth(graph, ctx) {
  const { t, rev } = ctx;
  const { precise, exportedTotal, dead, entryPoints } = deadExportRows(graph);
  const orphans = orphanFiles(graph);

  const deadShown = dead.slice(0, SAMPLE_N);
  const orphansShown = orphans.slice(0, SAMPLE_N);

  const out = [
    `# ${t('healthTitle')}`,
    '',
    header(t, rev),
    '',
    `> ${t('healthNote')}`,
    '',
    `## ${t('healthDead')}`,
    '',
    ...(precise ? [] : [t('healthDeadImprecise'), '']),
    t('healthDeadLine', { total: dead.length, exported: exportedTotal }),
    ...(entryPoints > 0 ? ['', t('healthDeadEntryPoints', { n: entryPoints })] : []),
    '',
    table(
      [t('colSymbol'), t('colKind'), t('colLocation')],
      deadShown.map((s) => [
        `\`${s.properties?.name ?? s.id}\``,
        `\`${s.properties?.kind ?? '?'}\``,
        `\`${s.properties?.path ?? ''}:${s.properties?.line ?? '?'}\``,
      ]),
      t,
    ),
    ...(dead.length > deadShown.length ? ['', t('andMore', { n: dead.length - deadShown.length })] : []),
    '',
    `## ${t('healthOrphans')}`,
    '',
    t('healthOrphansLine', { total: orphans.length }),
    '',
    table([t('colPath')], orphansShown.map((p) => [`\`${p}\``]), t),
    ...(orphans.length > orphansShown.length ? ['', t('andMore', { n: orphans.length - orphansShown.length })] : []),
  ];
  return `${out.join('\n')}\n`;
}

