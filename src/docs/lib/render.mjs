/** Escape the one character that would break a markdown table cell. */
const cell = (v) => String(v ?? '').replace(/\|/g, '\\|');

/** A markdown table, or the localized "none" line when there are no rows. */
function table(headers, rows, t) {
  if (rows.length === 0) return t('none');
  const head = `| ${headers.map(cell).join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.map(cell).join(' | ')} |`);
  return [head, sep, ...body].join('\n');
}

/** Ranked lists are cut at TOP_N with an explicit "and N more" line. */
function withMore(rows, t, limit = TOP_N) {
  const shown = rows.slice(0, limit);
  const rest = rows.length - shown.length;
  return { shown, moreLine: rest > 0 ? t('andMore', { n: rest }) : null };
}

/** Sort desc by `n`, ties broken by `key` ascending — stable across runs. */
const byCountThenName = (a, b) => b.n - a.n || (a.key < b.key ? -1 : a.key > b.key ? 1 : 0);

/** A file-system-safe, stable page name for a domain. */
function slugify(name) {
  const s = String(name).trim().replace(/[^\w.-]+/g, '-').replace(/^-+|-+$/g, '');
  return s.length > 0 ? s : 'domain';
}

