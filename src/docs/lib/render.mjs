/** Default language when none is given or the requested one is unknown. */
export const DEFAULT_LANG = 'en';

/** A `t(key, vars)` lookup bound to one language (unknown language → en). */
export function translator(lang) {
  const dict = STRINGS[lang] ?? STRINGS[DEFAULT_LANG];
  return (key, vars = {}) => {
    const raw = dict[key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
    if (Array.isArray(raw)) return raw;
    return String(raw).replace(/\{(\w+)\}/g, (m, name) => (
      Object.hasOwn(vars, name) ? String(vars[name]) : m
    ));
  };
}

